export function getSurahTranslation(surah, lang) {
  if (!surah) return '';
  if (lang === 'en') return surah.englishNameTranslation || surah.englishName || '';
  if (lang === 'ar') return surah.name || '';
  return SURAH_MEANINGS[lang]?.[surah.number] || surah.englishNameTranslation || '';
}

export function formatSurahOption(surah, lang) {
  if (!surah) return '';
  const translation = getSurahTranslation(surah, lang);
  if (lang === 'ar') {
    return `${surah.number}. ${surah.name}`;
  }
  return `${surah.number}. ${surah.name} — ${translation}`;
}

export function formatSurahHeader(surah, lang) {
  if (!surah) return '';
  const translation = getSurahTranslation(surah, lang);
  if (lang === 'ar') return surah.name;
  return translation ? `${surah.name} — ${translation}` : surah.name;
}
